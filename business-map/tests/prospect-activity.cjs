const assert=require('node:assert/strict');
const A=require('../prospect-activity.js');
const now=Date.UTC(2026,9,3,3),old=now-A.LIMIT;
const p=(extra={})=>({id:'p',type:'プロスペ',status:'appointment-open',cardUpdatedAt:old,...extra});
const state={members:[p(),p({id:'recent',cardUpdatedAt:old+1}),p({id:'abo',type:'ABO'}),p({id:'customer',type:'カスタマー'}),p({id:'missing',cardUpdatedAt:undefined}),p({id:'future',cardUpdatedAt:now+1}),p({id:'invalid',cardUpdatedAt:'garbage'})]};
assert(A.sweep(state,now));
assert.equal(state.members[0].status,'next-month');
assert.equal(state.members[0].cardUpdatedAt,old);
for(const member of state.members.slice(1))assert.equal(member.status,'appointment-open');
for(const member of state.members.slice(4))assert.equal(member.cardUpdatedAt,now);
assert.equal(A.sweep(state,now),false);
assert.equal(A.timestamp(new Date(old).toISOString(),now),old);
const restored=JSON.parse(JSON.stringify(state));
assert.equal(A.sweep(restored,now+1),true);
assert.equal(restored.members[1].status,'next-month');
const edited={members:[p({cardUpdatedAt:now})]};
assert.equal(A.sweep(edited,now+A.LIMIT-1),false);
assert.equal(A.sweep(edited,now+A.LIMIT),true);
assert.equal(edited.members[0].status,'next-month');
console.log('21-day boundary, legacy migration, non-prospects, persistence, edited card: passed');
