const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const style=()=>({setProperty(name,value){this[name]=value;}});
const nodes=Object.fromEntries(['mapCanvasArea','mapTopStage','v196FavoriteDock','mapLegendFooter','v107ZoomValue'].map(id=>[id,{style:style()}]));
const listeners={},events={};
let natural=2400;
const wrap={clientWidth:390,scrollLeft:0,scrollTop:0,getBoundingClientRect:()=>({left:0}),addEventListener:(name,fn)=>listeners[name]=fn};
const network={get scrollWidth(){return natural;},getBoundingClientRect:()=>({width:natural*(Number(nodes.mapCanvasArea.style.zoom)||1)})};
nodes.treeRows={querySelector:()=>network};
let bind;
const context={window:{innerWidth:390,addEventListener:(name,fn)=>events[name]=fn},document:{readyState:'loading',addEventListener:(name,fn)=>bind=fn,getElementById:id=>nodes[id],querySelector:()=>wrap},getComputedStyle:()=>({paddingLeft:'9px',paddingRight:'9px'}),requestAnimationFrame:fn=>{fn();return 1;},cancelAnimationFrame(){},Date};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../map-viewport.js'),'utf8'),context);
bind();
const viewport=context.window.MapViewport;
assert.equal(Number(nodes.mapCanvasArea.style.zoom),372/2416);
assert.equal(nodes.mapTopStage.style.width,'2416px');
for(const id of ['mapTopStage','v196FavoriteDock','mapLegendFooter'])assert.equal(nodes[id].style.zoom,nodes.mapCanvasArea.style.zoom);
viewport.setZoom(.52);
events.resize(); // Height-only resize must not refit after a manual zoom.
assert.equal(Number(nodes.mapCanvasArea.style.zoom),.52);
viewport.autoFit();assert.equal(Number(nodes.mapCanvasArea.style.zoom),.52);
context.window.innerWidth=844;wrap.clientWidth=844;events.resize();
assert.equal(Number(nodes.mapCanvasArea.style.zoom),.52);
viewport.fit();assert.equal(Number(nodes.mapCanvasArea.style.zoom),826/2416);
natural=600;viewport.fit();assert.equal(nodes.mapTopStage.style.width,'1120px');
assert.equal(Number(nodes.mapCanvasArea.style.zoom),826/1120);
viewport.setZoom(.5);
let prevented=0;
const touch=(x1,x2)=>({touches:[{clientX:x1,clientY:0},{clientX:x2,clientY:0}],preventDefault(){prevented++;}});
listeners.touchstart(touch(100,200));listeners.touchmove(touch(50,250));
assert.equal(Number(nodes.mapCanvasArea.style.zoom),1);
assert.equal(nodes.mapTopStage.style.zoom,'1');
assert.equal(prevented,2);
listeners.touchend({touches:[]});listeners.touchmove(touch(0,400));
assert.equal(Number(nodes.mapCanvasArea.style.zoom),1);
listeners.touchstart({touches:[{clientX:0,clientY:0}],preventDefault(){assert.fail('single-finger scrolling blocked');}});
viewport.setZoom(5);assert.equal(Number(nodes.mapCanvasArea.style.zoom),1.5);
viewport.setZoom(0);assert.equal(Number(nodes.mapCanvasArea.style.zoom),.02);
assert.match(fs.readFileSync(path.join(__dirname,'../v135-export.js'),'utf8'),/top\.style\.zoom='1'/);
console.log('Whole-map zoom, real fit, pinch, one-finger scroll, resize preservation and export reset: passed');
